#!/usr/bin/env python3
"""Build HeySQuAD SFT conversation parquets.

HUMAN variant
-------------
The audio-tokenization parquet runner can read HUMAN raw HuggingFace parquets
directly via ``audio.bytes`` and the stable raw ``id`` column, so HUMAN only
needs conversation parquets (no flattened ``data/``).

SQuAD-2.0 ``is_impossible`` rows have empty ``answers`` lists. We route every
row into one of three side-by-side conversation directories under
``processed/sft/hf___yijingwu___HeySQuAD_human/``:

* ``accepted/``           answerable rows (49,850). Assistant turn is the
                          first extractive answer from ``answers``.
* ``refusal_canonical/``  unanswerable rows (26,298). Assistant turn is a
                          canonical refusal phrase. Training-ready baseline.
* ``refusal_reasoned/``   unanswerable rows (26,298), to be populated later
                          by an LLM-enrichment pass that emits ``<think>``
                          reasoning + a context-grounded refusal. Stub
                          README only; not produced by this script.

All three consume the same shared SHAR + audio cache (built once over all
76,148 clips by the audio-tokenization pipeline). The cache is content-
addressed by ``audio_id``, so subset references are first-class.

MACHINE variant
---------------
MACHINE raw parquets lack a stable ``id`` column, so this script also writes
a flattened ``data/`` directory with a deterministic ``clip_id`` derived from
``audio.path``. The conversation output stays under ``examples/qa/``.

Usage:

    python convert_to_parquet.py --variant human
    python convert_to_parquet.py --variant machine
"""
from __future__ import annotations

import argparse
import glob
import io
import json
import sys
import time
import wave
from pathlib import Path

import polars as pl


DEFAULT_RAW_ROOT = Path(
    "/capstor/store/cscs/swissai/infra01/audio-datasets/raw"
)
DEFAULT_OUT_ROOT = Path(
    "/capstor/store/cscs/swissai/infra01/audio-datasets/processed/sft"
)

VARIANT_NAMES = ("human", "machine")
AUDIO_PLACEHOLDER = "<audio>"
# Canonical refusal phrasing for SQuAD-2.0 impossible questions. Training the
# model to commit to this exact string teaches "recognize when context is
# insufficient" — preferable to dropping the rows (loses negative-supervision
# signal) or using plausible_answers (actively trains hallucination).
DEFAULT_REFUSAL_TEMPLATE = (
    "The context does not provide enough information to answer this question."
)

REFUSAL_REASONED_README = """# refusal_reasoned/

This directory is reserved for an LLM-enriched version of the SQuAD-2.0
``is_impossible`` rows. Populate with a ``train.parquet`` whose assistant
turns contain reasoned refusals (optionally wrapped in ``<think>...</think>``
tags), generated by feeding (question_text, context, plausible_answers) to a
text or audio LLM.

Schema must match ``refusal_canonical/train.parquet`` so the audio-tokenizer
config can swap the ``conversations_dir`` without other changes.
"""


def parse_wav_metadata(audio_bytes: bytes) -> dict[str, float | int]:
    with wave.open(io.BytesIO(audio_bytes), "rb") as w:
        n = w.getnframes()
        sr = w.getframerate()
        return {
            "sampling_rate": sr,
            "num_frames": n,
            "duration_sec": n / sr if sr else 0.0,
        }


def _extract_human_shard(df: pl.DataFrame) -> pl.DataFrame:
    """Flatten audio Struct and surface raw SQuAD-2.0 fields.

    Keeps ``answers`` + ``is_impossible`` so the caller can route rows into
    accepted vs refusal subsets without re-reading.
    """
    return df.with_columns([
        pl.col("audio").struct.field("bytes").alias("audio_bytes"),
        pl.col("audio").struct.field("path").alias("audio_path"),
        pl.col("id").alias("clip_id"),
    ])


def _extract_machine_shard(df: pl.DataFrame) -> pl.DataFrame:
    """Flatten the audio Struct and derive clip_id for the MACHINE variant.

    MACHINE has no ``id`` column; we synthesize one from the (unique)
    ``audio.path`` field with a variant-scoped prefix to prevent
    cross-variant collisions when the cache is shared.
    """
    return df.with_columns([
        pl.col("audio").struct.field("bytes").alias("audio_bytes"),
        pl.col("audio").struct.field("path").alias("audio_path"),
        (
            pl.lit("heysquad_machine_")
            + pl.col("audio").struct.field("path").str.replace(r"\.wav$", "")
        ).alias("clip_id"),
    ])


def _attach_wav_metadata(df: pl.DataFrame) -> pl.DataFrame:
    """Decode WAV headers for every row; attach sampling_rate/num_frames/duration."""
    meta = [parse_wav_metadata(b) for b in df.get_column("audio_bytes").to_list()]
    return df.with_columns([
        pl.Series("duration_sec", [m["duration_sec"] for m in meta]),
        pl.Series("sampling_rate", [m["sampling_rate"] for m in meta]),
        pl.Series("num_frames", [m["num_frames"] for m in meta]),
        pl.lit("wav").alias("audio_format"),
    ])


def _make_row(*, clip_id, audio_path, duration_sec, question, transcription,
              context, answer, source_dataset) -> dict:
    msg = json.dumps(
        [
            {"role": "user",
             "content": f"{AUDIO_PLACEHOLDER}\n\nContext: {context}"},
            {"role": "assistant", "content": answer},
        ],
        ensure_ascii=False,
    )
    return {
        "sample_id": clip_id,
        "audio_ids": [clip_id],
        "messages_json": msg,
        "source_dataset": source_dataset,
        "audio_path": audio_path,
        "duration_sec": duration_sec,
        "question": question,
        "transcription": transcription,
        "answer": answer,
    }


def _write_manifest(out_dir: Path, *, n_rows: int, split: str,
                    source_variant: str, refusal: str | None) -> None:
    manifest = {
        "format": "audio_extractive_qa",
        "schema_version": 1,
        "n_rows": n_rows,
        "user_template": f"{AUDIO_PLACEHOLDER}\n\nContext: {{context}}",
        "assistant_template": "{answer}",
        "source_variant": source_variant,
        "split": split,
        "refusal_template": refusal,
    }
    with open(out_dir / "_MANIFEST.json", "w") as f:
        json.dump(manifest, f, indent=2)


def process_human(*, src_root: Path, dst_root: Path, refusal: str) -> tuple[int, int]:
    acc_dir = dst_root / "accepted"
    ref_dir = dst_root / "refusal_canonical"
    reasoned_dir = dst_root / "refusal_reasoned"
    acc_dir.mkdir(parents=True, exist_ok=True)
    ref_dir.mkdir(parents=True, exist_ok=True)
    reasoned_dir.mkdir(parents=True, exist_ok=True)

    in_files = sorted(glob.glob(str(src_root) + "/**/*.parquet", recursive=True))
    if not in_files:
        raise FileNotFoundError(f"no parquets under {src_root}")
    print(f"[human] {len(in_files)} input shards", flush=True)

    accepted_rows: list[dict] = []
    refusal_rows: list[dict] = []
    total = 0
    t0 = time.time()

    for i, path in enumerate(in_files):
        df = pl.read_parquet(
            path,
            columns=["audio", "id", "question", "transcription", "context",
                     "answers", "is_impossible"],
        )
        df = _extract_human_shard(df)
        df = _attach_wav_metadata(df)

        for r in df.filter(~pl.col("is_impossible")).iter_rows(named=True):
            accepted_rows.append(_make_row(
                clip_id=r["clip_id"], audio_path=r["audio_path"],
                duration_sec=r["duration_sec"], question=r["question"],
                transcription=r["transcription"], context=r["context"],
                answer=r["answers"][0]["text"],
                source_dataset="heysquad_human",
            ))

        for r in df.filter(pl.col("is_impossible")).iter_rows(named=True):
            refusal_rows.append(_make_row(
                clip_id=r["clip_id"], audio_path=r["audio_path"],
                duration_sec=r["duration_sec"], question=r["question"],
                transcription=r["transcription"], context=r["context"],
                answer=refusal,
                source_dataset="heysquad_human",
            ))

        total += len(df)
        print(
            f"  [human] shard {i+1}/{len(in_files)}  "
            f"running totals: accepted={len(accepted_rows):,} "
            f"refusal={len(refusal_rows):,}  "
            f"elapsed={time.time()-t0:.1f}s",
            flush=True,
        )

    pl.DataFrame(accepted_rows).write_parquet(str(acc_dir / "train.parquet"))
    pl.DataFrame(refusal_rows).write_parquet(str(ref_dir / "train.parquet"))
    _write_manifest(acc_dir, n_rows=len(accepted_rows), split="accepted",
                    source_variant="human", refusal=None)
    _write_manifest(ref_dir, n_rows=len(refusal_rows), split="refusal_canonical",
                    source_variant="human", refusal=refusal)
    (reasoned_dir / "_README.md").write_text(REFUSAL_REASONED_README)

    elapsed = time.time() - t0
    print(
        f"[human] DONE: accepted={len(accepted_rows):,}, "
        f"refusal_canonical={len(refusal_rows):,}, total={total:,}, "
        f"elapsed={elapsed:.1f}s",
        flush=True,
    )
    return len(accepted_rows), len(refusal_rows)


def process_machine(*, src_root: Path, dst_root: Path) -> int:
    (dst_root / "data").mkdir(parents=True, exist_ok=True)
    (dst_root / "examples" / "qa").mkdir(parents=True, exist_ok=True)

    in_files = sorted(glob.glob(str(src_root) + "/**/*.parquet", recursive=True))
    if not in_files:
        raise FileNotFoundError(f"no parquets under {src_root}")
    print(f"[machine] {len(in_files)} input shards", flush=True)

    conv_rows: list[dict] = []
    total_rows = 0
    t0 = time.time()

    for i, path in enumerate(in_files):
        df = pl.read_parquet(
            path,
            columns=["audio", "question", "transcription", "context", "answer"],
        )
        df = _extract_machine_shard(df)
        df = _attach_wav_metadata(df)

        data_cols = [
            "clip_id", "audio_bytes", "audio_format", "audio_path",
            "duration_sec", "sampling_rate", "num_frames",
            "question", "transcription", "context", "answer",
        ]
        out_data = dst_root / "data" / f"train-{i:05d}-of-{len(in_files):05d}.parquet"
        df.select(data_cols).write_parquet(str(out_data))

        for r in df.iter_rows(named=True):
            conv_rows.append(_make_row(
                clip_id=r["clip_id"], audio_path=r["audio_path"],
                duration_sec=r["duration_sec"], question=r["question"],
                transcription=r["transcription"], context=r["context"],
                answer=r["answer"],
                source_dataset="heysquad_machine",
            ))

        total_rows += len(df)
        print(
            f"  [machine] shard {i+1}/{len(in_files)}  "
            f"total_rows={total_rows:,}  elapsed={time.time()-t0:.1f}s",
            flush=True,
        )

    conv_df = pl.DataFrame(conv_rows)
    conv_df.write_parquet(str(dst_root / "examples" / "qa" / "train.parquet"))
    _write_manifest(dst_root / "examples" / "qa",
                    n_rows=len(conv_df), split="qa",
                    source_variant="machine", refusal=None)

    elapsed = time.time() - t0
    print(f"[machine] DONE: {len(conv_df):,} samples, elapsed={elapsed:.1f}s", flush=True)
    return len(conv_df)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument(
        "--variant",
        choices=VARIANT_NAMES,
        default=None,
        help="Process only this variant (default: both).",
    )
    p.add_argument(
        "--raw-root",
        type=Path,
        default=DEFAULT_RAW_ROOT,
        help="Parent of hf___yijingwu___HeySQuAD_{variant}/ raw dirs.",
    )
    p.add_argument(
        "--out-root",
        type=Path,
        default=DEFAULT_OUT_ROOT,
        help="Parent dir for hf___yijingwu___HeySQuAD_{variant}/ processed outputs.",
    )
    p.add_argument(
        "--refusal-template",
        default=DEFAULT_REFUSAL_TEMPLATE,
        help="Phrase used as assistant content for refusal_canonical (HUMAN only).",
    )
    args = p.parse_args(argv)

    variants = [args.variant] if args.variant else list(VARIANT_NAMES)
    for v in variants:
        src = args.raw_root / f"hf___yijingwu___HeySQuAD_{v}"
        dst = args.out_root / f"hf___yijingwu___HeySQuAD_{v}"
        if v == "human":
            process_human(src_root=src, dst_root=dst, refusal=args.refusal_template)
        else:
            process_machine(src_root=src, dst_root=dst)
    return 0


if __name__ == "__main__":
    sys.exit(main())
