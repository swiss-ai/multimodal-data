"""
Download SWISSIMAGE tiles using img2dataset.

Run generate_urls.py first, then:

    python download.py \
        --url-list swissimage_urls.csv \
        --output-dir /path/to/swissimage

Requirements:
    pip install img2dataset
"""

import argparse
import os

import img2dataset


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--url-list",
        required=True,
        help="CSV file with WMS URLs (generated by generate_urls.py)",
    )
    parser.add_argument("--output-dir", required=True, help="Output directory")
    parser.add_argument(
        "--processes-count",
        type=int,
        default=32,
        help="Number of download processes (default: 32)",
    )
    args = parser.parse_args()

    os.makedirs(args.output_dir, exist_ok=True)
    os.environ["NO_ALBUMENTATIONS_UPDATE"] = "1"

    img2dataset.download(
        url_list=args.url_list,
        output_folder=args.output_dir,
        processes_count=args.processes_count,
        resize_mode="no",
        output_format="webdataset",
        input_format="csv",
        url_col="url",
        number_sample_per_shard=100,
        timeout=120,
        retries=5,
    )


if __name__ == "__main__":
    main()
